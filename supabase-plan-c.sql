-- ─── M9. Vues : état des lignes et des commandes (calculé, jamais saisi) ───
create view public.achats_lignes_etat with (security_invoker = true) as
select l.*,
       coalesce(r.recu, 0)                                                   as qte_recue,
       greatest(0, l.qte_commandee - coalesce(r.recu, 0) - l.qte_annulee)    as reste,
       greatest(0, coalesce(r.recu, 0) - l.qte_commandee)                    as surplus
from public.achats_lignes l
left join (select ligne_id, sum(quantite)::int as recu from public.mouvements_stock where type = 'entree' group by ligne_id) r
  on r.ligne_id = l.id;

create view public.achats_commandes_etat with (security_invoker = true) as
select c.*,
       coalesce(s.commandee, 0)  as qte_commandee,
       coalesce(s.recue, 0)      as qte_recue,
       coalesce(s.annulee, 0)    as qte_annulee,
       coalesce(s.reste, 0)      as reste,
       coalesce(s.montant_net, 0) as montant_net,                 -- (commandé − annulé) × prix d'achat
       coalesce(s.hors, 0)       as lignes_hors_commande,
       case
         when coalesce(s.reste, 0) = 0 and coalesce(s.commandee, 0) + coalesce(s.recue, 0) > 0
           then case when c.type = 'reassort' then 'Reçu' else 'Soldée' end
         when c.type = 'reassort' then coalesce(c.etape, 'Demandé')
         when coalesce(s.recue, 0) = 0 then 'Commandée'
         else 'Partiellement reçue'
       end as statut
from public.achats_commandes c
left join (
  select commande_id,
         sum(qte_commandee)::int as commandee, sum(qte_recue)::int as recue, sum(qte_annulee)::int as annulee,
         sum(reste)::int as reste, sum((qte_commandee - qte_annulee) * prix_achat) as montant_net,
         count(*) filter (where hors_commande)::int as hors
  from public.achats_lignes_etat group by commande_id
) s on s.commande_id = c.id;

-- ─── M10. Déclencheur : la quantité annulée ne change que par la Direction (décision 10) ───
create function public.reliquat_reserve_direction() returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if new.qte_annulee is distinct from old.qte_annulee and not public.est_direction() then
    raise exception 'Annuler ou rétablir un reliquat est réservé à la Direction' using errcode = '42501';
  end if;
  return new;
end $$;
create trigger reliquat_reserve_direction before update on public.achats_lignes
  for each row execute function public.reliquat_reserve_direction();

-- ─── M11. Déclencheur : une réception rattachée ne s'écrit que par les fonctions de réception ───
-- (garde l'accord entre l'entrée, ses mouvements et le reste à livrer). Le pointage, le commentaire,
-- le prix (PHT) et la suppression restent permis comme aujourd'hui.
create function public.reception_par_fonction() returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if coalesce(current_setting('suivi_pro.par_fonction', true), '') = 'oui' then return new; end if;
  if tg_op = 'INSERT' then
    if new.commande_id is not null then
      raise exception 'Une réception rattachée à une commande s''enregistre par enregistrer_reception' using errcode = '42501';
    end if;
  elsif new.commande_id is distinct from old.commande_id
     or (old.commande_id is not null and
         (new.sizes, new.total, new.date, new.season, new.fournisseur_id, new.magasin_id, new.modele)
           is distinct from (old.sizes, old.total, old.date, old.season, old.fournisseur_id, old.magasin_id, old.modele)) then
    raise exception 'Une réception rattachée à une commande se corrige par corriger_reception' using errcode = '42501';
  end if;
  return new;
end $$;
create trigger reception_par_fonction before insert or update on public.entrees
  for each row execute function public.reception_par_fonction();

-- ─── M12. Fonction interne : mouvements d'un article reçu (modèle-coloris, quantités par taille) ───
-- Appelée par enregistrer_reception et corriger_reception (commande déjà verrouillée). Non appelable par l'application.
create function public.reception_article(p_commande public.achats_commandes, p_entree_id bigint, p_date date, p_article jsonb)
returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  v_code    text := btrim(coalesce(p_article ->> 'code_modele', ''));
  v_couleur text := btrim(coalesce(p_article ->> 'couleur', ''));
  v_ok_hors boolean := coalesce((p_article ->> 'confirme_hors_commande')::boolean, false);
  t record; l public.achats_lignes%rowtype;
  v_recu int; v_reste int; v_prix numeric; v_normal int; v_hors int;
  v_total int := 0; v_pht numeric := 0; v_sizes jsonb := '{}';
begin
  if v_code = '' then raise exception 'Article sans Code Modèle'; end if;
  for t in select key as taille, (value)::int as qte from jsonb_each_text(coalesce(p_article -> 'tailles', '{}')) loop
    continue when t.qte is null or t.qte <= 0;
    select * into l from public.achats_lignes
      where commande_id = p_commande.id and code_modele = v_code and couleur = v_couleur and taille = t.taille;
    if not found then
      -- article absent de la commande : accepté seulement après confirmation explicite (décision 7)
      if not v_ok_hors then
        raise exception 'HORS_COMMANDE : % % taille % n''est pas dans la commande', v_code, v_couleur, t.taille using errcode = 'P0001';
      end if;
      select prix_achat into v_prix from public.achats_lignes
        where commande_id = p_commande.id and code_modele = v_code and couleur = v_couleur order by id limit 1;
      insert into public.achats_lignes (commande_id, ordre, marque, code_modele, libelle, couleur, taille, prix_achat, qte_commandee, hors_commande)
      values (p_commande.id, 999999, coalesce(p_article ->> 'marque', ''), v_code, coalesce(p_article ->> 'libelle', ''),
              v_couleur, t.taille, coalesce(v_prix, 0), 0, true)
      returning * into l;
      v_normal := 0; v_hors := t.qte;
    else
      select coalesce(sum(quantite), 0) into v_recu from public.mouvements_stock where ligne_id = l.id and type = 'entree';
      v_reste := greatest(0, l.qte_commandee - v_recu - l.qte_annulee);
      v_normal := least(t.qte, v_reste); v_hors := t.qte - v_normal;
      if v_hors > 0 and not v_ok_hors then
        raise exception 'AU_DELA_DU_RESTE : % % taille % : % reçue(s) pour un reste de %', v_code, v_couleur, t.taille, t.qte, v_reste using errcode = 'P0001';
      end if;
    end if;
    if v_normal > 0 then
      insert into public.mouvements_stock (date, magasin_id, fournisseur_id, season, code_modele, couleur, taille, gencode, quantite, type, entree_id, ligne_id, hors_commande)
      values (p_date, p_commande.magasin_id, p_commande.fournisseur_id, p_commande.season, l.code_modele, l.couleur, l.taille, l.gencode, v_normal, 'entree', p_entree_id, l.id, l.hors_commande);
    end if;
    if v_hors > 0 then
      insert into public.mouvements_stock (date, magasin_id, fournisseur_id, season, code_modele, couleur, taille, gencode, quantite, type, entree_id, ligne_id, hors_commande)
      values (p_date, p_commande.magasin_id, p_commande.fournisseur_id, p_commande.season, l.code_modele, l.couleur, l.taille, l.gencode, v_hors, 'entree', p_entree_id, l.id, true);
    end if;
    v_total := v_total + t.qte;
    v_pht   := v_pht + t.qte * l.prix_achat;               -- prix de la ligne au moment de la réception (figé ensuite)
    v_sizes := v_sizes || jsonb_build_object(t.taille, t.qte);
  end loop;
  if v_total = 0 then raise exception 'Article % % sans quantité', v_code, v_couleur; end if;
  return jsonb_build_object('total', v_total, 'pht', round(v_pht, 2), 'sizes', v_sizes,
                            'modele', case when v_couleur <> '' then v_code || ', ' || v_couleur else v_code end);
end $$;

-- ─── M13. Enregistrer une réception (tous les comptes connectés) ───
-- p_date « JJ/MM/AAAA » (format du Cahier) ; p_articles = [{ code_modele, couleur, tailles: { "38": 2, … },
--   confirme_hors_commande, numero, categorie, type_key, marque, libelle }, …] ; une entrée par modèle-coloris.
-- Renvoie les id des entrées créées.
create function public.enregistrer_reception(p_commande_id bigint, p_date text, p_articles jsonb, p_commentaire text default '')
returns bigint[]
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  c public.achats_commandes%rowtype; v_date date; a jsonb; r jsonb; v_id bigint; v_ids bigint[] := '{}';
begin
  if auth.uid() is null then raise exception 'Connexion requise' using errcode = '28000'; end if;
  select * into c from public.achats_commandes where id = p_commande_id for update;   -- une réception à la fois par commande
  if not found then raise exception 'Commande introuvable'; end if;
  v_date := to_date(p_date, 'DD/MM/YYYY');
  if jsonb_typeof(p_articles) is distinct from 'array' or jsonb_array_length(p_articles) = 0 then raise exception 'Aucun article'; end if;
  perform set_config('suivi_pro.par_fonction', 'oui', true);
  for a in select value from jsonb_array_elements(p_articles) loop
    insert into public.entrees (magasin_id, fournisseur_id, date, statut, season, modele, numero, categorie, type_key, total, pht, sizes, commentaire, commande_id)
    values (c.magasin_id, c.fournisseur_id, p_date, case when c.type = 'reassort' then 'Réassort' else '' end, c.season, '',
            coalesce(a ->> 'numero', ''), coalesce(a ->> 'categorie', ''), coalesce(a ->> 'type_key', 'F'), 0, 0, '{}',
            coalesce(p_commentaire, ''), c.id)
    returning id into v_id;
    r := public.reception_article(c, v_id, v_date, a);
    update public.entrees set modele = r ->> 'modele', total = (r ->> 'total')::int, pht = (r ->> 'pht')::numeric, sizes = r -> 'sizes'
      where id = v_id;
    v_ids := v_ids || v_id;
  end loop;
  perform set_config('suivi_pro.par_fonction', '', true);
  return v_ids;
end $$;

-- ─── M14. Corriger une réception (mêmes comptes qu'aujourd'hui pour corriger une entrée) ───
-- Réécrit les mouvements de l'entrée ; p_article comme un élément de p_articles ci-dessus.
create function public.corriger_reception(p_entree_id bigint, p_date text, p_article jsonb)
returns void
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare e public.entrees%rowtype; c public.achats_commandes%rowtype; r jsonb;
begin
  if auth.uid() is null then raise exception 'Connexion requise' using errcode = '28000'; end if;
  select * into e from public.entrees where id = p_entree_id;
  if not found or e.commande_id is null then raise exception 'Réception rattachée introuvable'; end if;
  select * into c from public.achats_commandes where id = e.commande_id for update;
  perform set_config('suivi_pro.par_fonction', 'oui', true);
  delete from public.mouvements_stock where entree_id = e.id;
  r := public.reception_article(c, e.id, to_date(p_date, 'DD/MM/YYYY'), p_article);
  update public.entrees set date = p_date, modele = r ->> 'modele', total = (r ->> 'total')::int, pht = (r ->> 'pht')::numeric, sizes = r -> 'sizes'
    where id = e.id;
  perform set_config('suivi_pro.par_fonction', '', true);
end $$;

-- ─── M15. Importer une commande (Direction) : une commande par magasin du fichier, tout ou rien ───
-- p_infos = { fournisseur_id, season, type, numeros_bc: [...], date_commande "AAAA-MM-JJ", livraison_prevue, fichier }
-- p_lignes = [{ magasin_id, ordre, collection, magasin_fichier, marque, gencode, code_modele, libelle, couleur, taille,
--   rayon, famille, sous_famille, prix_achat, pvc, chaussant, hauteur_talon, matiere, semelle_exterieure, fermeture,
--   saison_polaris, qte_commandee }, …] (magasin_id retrouvé par l'application dans magasins_correspondance).
-- Un même article présent deux fois (deux BC) : quantités additionnées, à condition que le prix soit le même.
create function public.importer_commande(p_infos jsonb, p_lignes jsonb)
returns bigint[]
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  v_season text := p_infos ->> 'season'; v_type text := coalesce(p_infos ->> 'type', 'saison');
  m bigint; v_cmd bigint; v_ids bigint[] := '{}'; l jsonb; v_prix numeric;
begin
  if not public.est_direction() then raise exception 'Importer une commande est réservé à la Direction' using errcode = '42501'; end if;
  if not public.saison_suivie_par_commandes(v_season) then raise exception 'La saison % n''est pas suivie par commandes', v_season; end if;
  if jsonb_typeof(p_lignes) is distinct from 'array' or jsonb_array_length(p_lignes) = 0 then raise exception 'Aucune ligne'; end if;
  for m in select distinct (value ->> 'magasin_id')::bigint from jsonb_array_elements(p_lignes) loop
    if m is null or not exists (select 1 from public.magasins where id = m) then raise exception 'Magasin inconnu dans le fichier'; end if;
    insert into public.achats_commandes (fournisseur_id, magasin_id, season, type, etape, numeros_bc, date_commande, livraison_prevue, fichier)
    values ((p_infos ->> 'fournisseur_id')::bigint, m, v_season, v_type, case when v_type = 'reassort' then 'Commandé' end,
            coalesce(array(select jsonb_array_elements_text(p_infos -> 'numeros_bc')), '{}'),
            nullif(p_infos ->> 'date_commande', '')::date, nullif(p_infos ->> 'livraison_prevue', '')::date, coalesce(p_infos ->> 'fichier', ''))
    returning id into v_cmd;
    for l in select value from jsonb_array_elements(p_lignes) where (value ->> 'magasin_id')::bigint = m loop
      v_prix := coalesce(nullif(l ->> 'prix_achat', '')::numeric, 0);
      insert into public.achats_lignes (commande_id, ordre, collection, magasin_fichier, marque, gencode, code_modele, libelle, couleur, taille,
        rayon, famille, sous_famille, prix_achat, pvc, chaussant, hauteur_talon, matiere, semelle_exterieure, fermeture, saison_polaris, qte_commandee)
      values (v_cmd, coalesce((l ->> 'ordre')::int, 0), coalesce(l ->> 'collection', ''), coalesce(l ->> 'magasin_fichier', ''), coalesce(l ->> 'marque', ''),
        coalesce(l ->> 'gencode', ''), btrim(coalesce(l ->> 'code_modele', '')), coalesce(l ->> 'libelle', ''), btrim(coalesce(l ->> 'couleur', '')),
        coalesce(l ->> 'taille', ''), coalesce(l ->> 'rayon', ''), coalesce(l ->> 'famille', ''), coalesce(l ->> 'sous_famille', ''), v_prix,
        nullif(l ->> 'pvc', '')::numeric, coalesce(l ->> 'chaussant', ''), coalesce(l ->> 'hauteur_talon', ''), coalesce(l ->> 'matiere', ''),
        coalesce(l ->> 'semelle_exterieure', ''), coalesce(l ->> 'fermeture', ''), coalesce(l ->> 'saison_polaris', ''), coalesce((l ->> 'qte_commandee')::int, 0))
      on conflict (commande_id, code_modele, couleur, taille) do update
        set qte_commandee = achats_lignes.qte_commandee + excluded.qte_commandee
        where achats_lignes.prix_achat = excluded.prix_achat;
      if not found then
        raise exception 'Article % % taille % présent deux fois avec deux prix différents', l ->> 'code_modele', l ->> 'couleur', l ->> 'taille';
      end if;
    end loop;
    insert into public.achats_journal (commande_id, action, detail)
    values (v_cmd, 'import', jsonb_build_object('fichier', p_infos ->> 'fichier',
      'lignes', (select count(*) from public.achats_lignes where commande_id = v_cmd),
      'paires', (select sum(qte_commandee) from public.achats_lignes where commande_id = v_cmd)));
    v_ids := v_ids || v_cmd;
  end loop;
  return v_ids;
end $$;

-- ─── M16. Réimporter une commande (Direction, décision 5) ───
-- p_lignes comme pour importer_commande (sans magasin_id) ; p_infos facultatif (numeros_bc, dates, fichier).
-- p_essai = true : renvoie seulement le récapitulatif des changements, sans rien modifier (aperçu avant validation).
-- Règles : les quantités reçues ne bougent jamais ; une quantité commandée ne descend pas sous la quantité reçue ;
-- un article absent du fichier sort de la commande s'il n'a jamais été reçu, sinon sa quantité commandée est ramenée
-- au reçu ; un article hors commande retrouvé dans le fichier devient un article commandé. Le nouveau prix ne
-- s'applique qu'aux réceptions suivantes (le PHT des réceptions enregistrées est figé).
create function public.reimporter_commande(p_commande_id bigint, p_lignes jsonb, p_infos jsonb default '{}', p_essai boolean default true)
returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  c public.achats_commandes%rowtype; n record; x record;
  v_ajouts jsonb := '[]'; v_qtes jsonb := '[]'; v_prix jsonb := '[]'; v_retraits jsonb := '[]'; v_bloques jsonb := '[]';
  v_q int; v_res jsonb;
begin
  if not public.est_direction() then raise exception 'Réimporter une commande est réservé à la Direction' using errcode = '42501'; end if;
  select * into c from public.achats_commandes where id = p_commande_id for update;
  if not found then raise exception 'Commande introuvable'; end if;

  -- nouvelles lignes, regroupées par article (deux BC → quantités additionnées)
  create temporary table _nouv on commit drop as
  select btrim(coalesce(value ->> 'code_modele', '')) as code_modele, btrim(coalesce(value ->> 'couleur', '')) as couleur,
         coalesce(value ->> 'taille', '') as taille,
         sum(coalesce((value ->> 'qte_commandee')::int, 0))::int as qte,
         max(coalesce(nullif(value ->> 'prix_achat', '')::numeric, 0)) as prix,
         count(distinct coalesce(nullif(value ->> 'prix_achat', '')::numeric, 0)) as nb_prix,
         (array_agg(value order by coalesce((value ->> 'ordre')::int, 0)))[1] as brut
  from jsonb_array_elements(p_lignes) group by 1, 2, 3;
  if exists (select 1 from _nouv where code_modele = '') then raise exception 'Ligne sans Code Modèle'; end if;
  if exists (select 1 from _nouv where nb_prix > 1) then raise exception 'Un article apparaît avec deux prix différents'; end if;

  -- comparaison avec la commande actuelle
  for x in
    select e.id, e.code_modele, e.couleur, e.taille, e.qte_commandee, e.qte_recue, e.qte_annulee, e.prix_achat, e.hors_commande,
           nv.qte as n_qte, nv.prix as n_prix, nv.brut, (nv.code_modele is not null) as dans_fichier
    from public.achats_lignes_etat e
    left join _nouv nv on (nv.code_modele, nv.couleur, nv.taille) = (e.code_modele, e.couleur, e.taille)
    where e.commande_id = c.id
  loop
    if not x.dans_fichier then
      if x.qte_recue = 0 then
        v_retraits := v_retraits || jsonb_build_object('article', x.code_modele || ' ' || x.couleur || ' ' || x.taille, 'qte', x.qte_commandee);
        if not p_essai then delete from public.achats_lignes where id = x.id; end if;
      elsif x.qte_commandee > x.qte_recue then
        v_qtes := v_qtes || jsonb_build_object('article', x.code_modele || ' ' || x.couleur || ' ' || x.taille, 'avant', x.qte_commandee, 'apres', x.qte_recue, 'raison', 'absent du fichier, déjà reçu');
        if not p_essai then
          update public.achats_lignes set qte_commandee = x.qte_recue, qte_annulee = 0 where id = x.id;
        end if;
      end if;
    else
      v_q := greatest(x.n_qte, x.qte_recue);
      if x.n_qte < x.qte_recue then
        v_bloques := v_bloques || jsonb_build_object('article', x.code_modele || ' ' || x.couleur || ' ' || x.taille, 'fichier', x.n_qte, 'recu', x.qte_recue);
      end if;
      if v_q <> x.qte_commandee or x.hors_commande then
        v_qtes := v_qtes || jsonb_build_object('article', x.code_modele || ' ' || x.couleur || ' ' || x.taille, 'avant', x.qte_commandee, 'apres', v_q);
      end if;
      if x.n_prix <> x.prix_achat then
        v_prix := v_prix || jsonb_build_object('article', x.code_modele || ' ' || x.couleur || ' ' || x.taille, 'avant', x.prix_achat, 'apres', x.n_prix);
      end if;
      if not p_essai then
        update public.achats_lignes set
          qte_commandee = v_q,
          qte_annulee   = greatest(0, least(qte_annulee, v_q - x.qte_recue)),
          prix_achat    = x.n_prix,
          hors_commande = false,
          gencode = coalesce(x.brut ->> 'gencode', gencode), libelle = coalesce(x.brut ->> 'libelle', libelle),
          rayon = coalesce(x.brut ->> 'rayon', rayon), famille = coalesce(x.brut ->> 'famille', famille),
          sous_famille = coalesce(x.brut ->> 'sous_famille', sous_famille), pvc = coalesce(nullif(x.brut ->> 'pvc', '')::numeric, pvc),
          chaussant = coalesce(x.brut ->> 'chaussant', chaussant), hauteur_talon = coalesce(x.brut ->> 'hauteur_talon', hauteur_talon),
          matiere = coalesce(x.brut ->> 'matiere', matiere), semelle_exterieure = coalesce(x.brut ->> 'semelle_exterieure', semelle_exterieure),
          fermeture = coalesce(x.brut ->> 'fermeture', fermeture), saison_polaris = coalesce(x.brut ->> 'saison_polaris', saison_polaris),
          ordre = coalesce((x.brut ->> 'ordre')::int, ordre)
        where id = x.id;
      end if;
    end if;
  end loop;

  -- articles nouveaux
  for n in select * from _nouv nv where not exists (
      select 1 from public.achats_lignes l where l.commande_id = c.id and (l.code_modele, l.couleur, l.taille) = (nv.code_modele, nv.couleur, nv.taille)) loop
    v_ajouts := v_ajouts || jsonb_build_object('article', n.code_modele || ' ' || n.couleur || ' ' || n.taille, 'qte', n.qte, 'prix', n.prix);
    if not p_essai then
      insert into public.achats_lignes (commande_id, ordre, collection, magasin_fichier, marque, gencode, code_modele, libelle, couleur, taille,
        rayon, famille, sous_famille, prix_achat, pvc, chaussant, hauteur_talon, matiere, semelle_exterieure, fermeture, saison_polaris, qte_commandee)
      values (c.id, coalesce((n.brut ->> 'ordre')::int, 0), coalesce(n.brut ->> 'collection', ''), coalesce(n.brut ->> 'magasin_fichier', ''),
        coalesce(n.brut ->> 'marque', ''), coalesce(n.brut ->> 'gencode', ''), n.code_modele, coalesce(n.brut ->> 'libelle', ''), n.couleur, n.taille,
        coalesce(n.brut ->> 'rayon', ''), coalesce(n.brut ->> 'famille', ''), coalesce(n.brut ->> 'sous_famille', ''), n.prix,
        nullif(n.brut ->> 'pvc', '')::numeric, coalesce(n.brut ->> 'chaussant', ''), coalesce(n.brut ->> 'hauteur_talon', ''),
        coalesce(n.brut ->> 'matiere', ''), coalesce(n.brut ->> 'semelle_exterieure', ''), coalesce(n.brut ->> 'fermeture', ''),
        coalesce(n.brut ->> 'saison_polaris', ''), n.qte);
    end if;
  end loop;

  v_res := jsonb_build_object('ajouts', v_ajouts, 'quantites', v_qtes, 'prix', v_prix, 'retraits', v_retraits,
                              'sous_le_recu', v_bloques, 'essai', p_essai);
  if not p_essai then
    update public.achats_commandes set
      numeros_bc       = case when p_infos ? 'numeros_bc' then array(select jsonb_array_elements_text(p_infos -> 'numeros_bc')) else numeros_bc end,
      date_commande    = coalesce(nullif(p_infos ->> 'date_commande', '')::date, date_commande),
      livraison_prevue = coalesce(nullif(p_infos ->> 'livraison_prevue', '')::date, livraison_prevue),
      fichier          = coalesce(nullif(p_infos ->> 'fichier', ''), fichier),
      reimporte_par = auth.uid(), reimporte_le = now()
    where id = c.id;
    insert into public.achats_journal (commande_id, action, detail) values (c.id, 'reimport', v_res);
  end if;
  return v_res;
end $$;

-- ─── M17. Annuler ou rétablir un reliquat (Direction, motif obligatoire dans les deux sens, décision 10) ───
-- p_ligne_id vide = toute la commande ; p_sens 'annuler' ou 'retablir'. Renvoie le nombre de lignes modifiées.
create function public.annuler_retablir_reliquat(p_commande_id bigint, p_sens text, p_motif text, p_ligne_id bigint default null)
returns integer
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare v_n int; v_detail jsonb;
begin
  if not public.est_direction() then raise exception 'Réservé à la Direction' using errcode = '42501'; end if;
  if btrim(coalesce(p_motif, '')) = '' then raise exception 'Motif obligatoire'; end if;
  if p_sens not in ('annuler', 'retablir') then raise exception 'Sens inconnu : %', p_sens; end if;
  perform 1 from public.achats_commandes where id = p_commande_id for update;
  if not found then raise exception 'Commande introuvable'; end if;
  select coalesce(jsonb_agg(jsonb_build_object('ligne', e.id, 'article', e.code_modele || ' ' || e.couleur || ' ' || e.taille,
           'avant', e.qte_annulee, 'apres', case when p_sens = 'annuler' then e.qte_annulee + e.reste else 0 end)), '[]')
    into v_detail
  from public.achats_lignes_etat e
  where e.commande_id = p_commande_id and (p_ligne_id is null or e.id = p_ligne_id)
    and (case when p_sens = 'annuler' then e.reste > 0 else e.qte_annulee > 0 end);
  update public.achats_lignes l set qte_annulee = (d.v ->> 'apres')::int
  from jsonb_array_elements(v_detail) as d(v) where l.id = (d.v ->> 'ligne')::bigint;
  get diagnostics v_n = row_count;
  if v_n > 0 then
    insert into public.achats_journal (commande_id, action, motif, detail)
    values (p_commande_id, case when p_sens = 'annuler' then 'annulation' else 'retablissement' end, btrim(p_motif),
            jsonb_build_object('ligne', p_ligne_id, 'lignes', v_detail));
  end if;
  return v_n;
end $$;

