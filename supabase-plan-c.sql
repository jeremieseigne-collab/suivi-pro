-- ─── M1. Forme de comparaison d'un texte (sans majuscules, accents, espaces ni tirets) ───
-- Même règle que formeMagasin (src/commandes/constants.js) : « 3 Bailly Rouffiac » → « 3baillyrouffiac »
create function public.forme_texte(t text) returns text
language sql immutable parallel safe
set search_path = public, pg_temp
as $$
  select regexp_replace(
    lower(translate(coalesce(t, ''),
      'ÀÂÄÁÃÅàâäáãåÇçÉÈÊËéèêëÍÌÎÏíìîïÑñÓÒÔÖÕóòôöõÚÙÛÜúùûüÝýÿ',
      'AAAAAAaaaaaaCcEEEEeeeeIIIIiiiiNnOOOOOoooooUUUUuuuuYyy')),
    '[^a-z0-9]', '', 'g')
$$;

-- ─── M2. Saison suivie par commandes : Été 2027 et après (décision 14) ───
-- Clé de saison « ETE_2027 » / « HIVER_2027 » ; ordre = année × 2 + (hiver ? 1 : 0), comme ordreSaison (src/savdef/regles.js)
create function public.saison_suivie_par_commandes(p_saison text) returns boolean
language sql immutable parallel safe
set search_path = public, pg_temp
as $$
  select coalesce(
    (substring(p_saison from '_([0-9]{4})$'))::int * 2 + (case when p_saison like 'HIVER%' then 1 else 0 end) >= 2027 * 2,
    false)
$$;

-- ─── M3. Table de correspondance des magasins (décision 3) ───
create table public.magasins_correspondance (
  id           bigint generated by default as identity primary key,
  valeur       text   not null,                                   -- tel qu'écrit dans le fichier (« 1 Bailly Albi »)
  valeur_forme text   generated always as (public.forme_texte(valeur)) stored unique,
  magasin_id   bigint not null references public.magasins(id) on delete cascade,
  cree_le      timestamptz not null default now()
);
-- Les 3 correspondances décidées ; chaque magasin est retrouvé par le début de son nom (forme sans espaces ni accents).
-- Si un nom ne correspond pas à exactement un magasin, tout le fichier est annulé (aucune correspondance devinée).
insert into public.magasins_correspondance (valeur, magasin_id)
select v.valeur, (select m.id from public.magasins m where public.forme_texte(m.nom) like v.motif)
from (values ('1 Bailly Albi', 'baillyalbi%'), ('2 Les 2 Zèbres', 'les2zebres%'), ('3 Bailly Rouffiac', 'baillyrouffiac%')) as v(valeur, motif);

