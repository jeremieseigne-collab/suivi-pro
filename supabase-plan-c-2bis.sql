-- Plan C, étape 2 bis : fournisseurs et marques (PLAN-REFONTE.md, « Étape 2 bis »)
--
-- Un fournisseur (table fournisseurs_reels) a une ou plusieurs marques ; une marque (table fournisseurs, nom
-- historique) a toujours exactement un fournisseur. Le règlement (modes, délais, plans chèques) se fait au
-- fournisseur ; aucun calcul du Plan de règlement ne change (clés de pointage conservées).
-- Rien n'est effacé dans les tables existantes : fournisseurs.groupe, modes_reglement, parametres.cheques et les
-- contacts des marques restent en place (plus lus). Annulation : supabase-plan-c-2bis-annulation.sql.
-- Décisions du 14/10 : nom = « Fournisseur réel » s'il existe, sinon la marque pilote (Q1) ; contacts recopiés
-- au fournisseur seulement s'ils sont communs à toutes ses marques, rien d'effacé (Q2) ; comptabilité, adresse,
-- notes au fournisseur (Q3) ; fournisseur sans marque gardé, supprimable par la Direction s'il n'a ni pointage ni
-- plan chèque (Q4) ; fusion : pointages rattachés au fournisseur gardé (Q5) ; nom de fournisseur non unique,
-- le rattachement à un homonyme est proposé par l'écran, jamais imposé (Q7) ; contacts modifiables par tous,
-- rattachement des marques, nom et règlement réservés à la Direction (Q9).
-- Une seule transaction : en cas d'erreur, rien n'est appliqué.
-- ═══════════════════════════════════════════════════════════════════════════════

begin;

-- ─── N1. Fournisseurs ───
create table public.fournisseurs_reels (
  id             bigint generated by default as identity primary key,
  nom            text   not null check (btrim(nom) <> ''),
  -- contacts : par magasin (coords_magasin, mêmes clés que les marques) et communs (mêmes colonnes que les marques)
  coords_magasin jsonb  not null default '{}',
  contact        text   not null default '', telephone text not null default '', email text not null default '',
  contact_sav    text   not null default '', telephone_fixe text not null default '', numero_client text not null default '',
  btob           text   not null default '',
  -- société (Q3)
  contact_compta text   not null default '', tel_compta text not null default '', email_compta text not null default '',
  adresse        text   not null default '', notes text not null default '',
  -- clé des pointages de chèques du Plan (« cheque|<cle>|magasin|saison|rang ») : n° de l'ancienne marque pilote pour
  -- les fournisseurs convertis (les pointages existants restent valables), « f<n°> » pour les nouveaux
  cle_pointage   text   unique,
  cree_le        timestamptz not null default now()
);
create index fournisseurs_reels_forme on public.fournisseurs_reels (public.forme_texte(nom));

create function public.fournisseur_cle_pointage() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  if new.cle_pointage is null or btrim(new.cle_pointage) = '' then new.cle_pointage := 'f' || new.id; end if;
  return new;
end $$;
create trigger fournisseur_cle_pointage before insert on public.fournisseurs_reels
  for each row execute function public.fournisseur_cle_pointage();

-- ─── N2. La marque → son fournisseur (obligatoire après la conversion, N7) ───
alter table public.fournisseurs add column fournisseur_reel_id bigint references public.fournisseurs_reels(id) on delete restrict;
create index fournisseurs_fournisseur_reel on public.fournisseurs (fournisseur_reel_id);

-- ─── N3. La marque hérite des contacts de son fournisseur (ses anciens champs restent, plus lus) ───
-- Défaut « oui » pour les nouvelles marques (leurs contacts se saisissent au fournisseur) ; la conversion (N7) le fixe.
alter table public.fournisseurs add column contacts_herites boolean not null default true;

-- ─── N5. Règlement au fournisseur (mode et conditions par magasin) ───
create table public.reglements_fournisseurs (
  id                  bigint generated by default as identity primary key,
  fournisseur_reel_id bigint not null references public.fournisseurs_reels(id) on delete cascade,
  magasin_id          bigint not null references public.magasins(id) on delete cascade,
  mode_reglement      text   not null default '',
  condition           jsonb  not null default '{}',
  unique (fournisseur_reel_id, magasin_id)
);

-- ─── N6. Plans chèques personnalisés au fournisseur (par magasin et saison) ───
create table public.plans_cheques (
  id                  bigint generated by default as identity primary key,
  fournisseur_reel_id bigint not null references public.fournisseurs_reels(id) on delete restrict,
  magasin_id          bigint not null references public.magasins(id) on delete cascade,
  season              text   not null,
  cheques             jsonb  not null default '[]',
  unique (fournisseur_reel_id, magasin_id, season)
);

-- ─── N7. Conversion des marques et groupes existants ───
-- Contacts d'une marque, sans les valeurs vides (pour savoir si toutes les marques d'un fournisseur ont les mêmes)
create function public.signature_contacts(f public.fournisseurs) returns jsonb
language sql immutable set search_path = public, pg_temp as $$
  select jsonb_build_object(
    'commun', (select coalesce(jsonb_object_agg(k, v), '{}') from (values
        ('contact', f.contact), ('telephone', f.telephone), ('email', f.email), ('contact_sav', f.contact_sav),
        ('telephone_fixe', f.telephone_fixe), ('numero_client', f.numero_client), ('btob', f.btob)) x(k, v)
      where btrim(coalesce(v, '')) <> ''),
    'magasins', (select coalesce(jsonb_object_agg(m.key, m.c), '{}') from (
        select key, (select jsonb_object_agg(k2, v2) from jsonb_each_text(value) e(k2, v2) where btrim(coalesce(v2, '')) <> '') c
        from jsonb_each(case when jsonb_typeof(f.coords_magasin) = 'object' then f.coords_magasin else '{}' end)
        where jsonb_typeof(value) = 'object') m where m.c is not null))
$$;
create function public.signature_societe(f public.fournisseurs) returns jsonb
language sql immutable set search_path = public, pg_temp as $$
  select jsonb_build_object('contact_compta', btrim(coalesce(f.contact_compta, '')), 'tel_compta', btrim(coalesce(f.tel_compta, '')),
    'email_compta', btrim(coalesce(f.email_compta, '')), 'adresse', btrim(coalesce(f.adresse, '')), 'notes', btrim(coalesce(f.notes, '')))
$$;

do $$
declare
  g record; v_fr bigint; v_ref public.fournisseurs%rowtype; v_contacts_communs boolean; v_societe_commune boolean;
  n_marques int; n_fr int; n_modes int; n_plans int; n_attendu_modes int; n_attendu_plans int;
begin
  -- Groupes : clé = « Fournisseur réel » s'il est renseigné, sinon le nom de la marque (règle actuelle du Plan) ;
  -- pilote = plus petit n° du groupe
  for g in
    select coalesce(nullif(btrim(groupe), ''), nom) as cle, array_agg(id order by id) as ids
    from public.fournisseurs group by 1 order by 1
  loop
    select * into v_ref from public.fournisseurs where id = g.ids[1];
    select count(distinct public.signature_contacts(f)) = 1, count(distinct public.signature_societe(f)) = 1
      into v_contacts_communs, v_societe_commune
      from public.fournisseurs f where f.id = any(g.ids);
    insert into public.fournisseurs_reels (nom, cle_pointage) values (g.cle, g.ids[1]::text) returning id into v_fr;
    -- contacts communs à toutes les marques → recopiés au fournisseur (Q2) ; les marques en héritent
    if v_contacts_communs then
      update public.fournisseurs_reels set
        coords_magasin = coalesce(case when jsonb_typeof(v_ref.coords_magasin) = 'object' then v_ref.coords_magasin end, '{}'),
        contact = coalesce(v_ref.contact, ''), telephone = coalesce(v_ref.telephone, ''), email = coalesce(v_ref.email, ''),
        contact_sav = coalesce(v_ref.contact_sav, ''), telephone_fixe = coalesce(v_ref.telephone_fixe, ''),
        numero_client = coalesce(v_ref.numero_client, ''), btob = coalesce(v_ref.btob, '')
      where id = v_fr;
    end if;
    -- comptabilité, adresse, notes : au fournisseur si communes à toutes ses marques (Q3)
    if v_societe_commune then
      update public.fournisseurs_reels set
        contact_compta = coalesce(v_ref.contact_compta, ''), tel_compta = coalesce(v_ref.tel_compta, ''),
        email_compta = coalesce(v_ref.email_compta, ''), adresse = coalesce(v_ref.adresse, ''), notes = coalesce(v_ref.notes, '')
      where id = v_fr;
    end if;
    update public.fournisseurs set fournisseur_reel_id = v_fr, contacts_herites = v_contacts_communs where id = any(g.ids);
    -- règlement : celui de la marque pilote (seul lu par le Plan aujourd'hui)
    insert into public.reglements_fournisseurs (fournisseur_reel_id, magasin_id, mode_reglement, condition)
    select v_fr, m.magasin_id, coalesce(m.mode_reglement, ''), coalesce(m.condition, '{}')
    from public.modes_reglement m where m.fournisseur_id = g.ids[1] and m.magasin_id is not null
      and exists (select 1 from public.magasins mg where mg.id = m.magasin_id)
    on conflict (fournisseur_reel_id, magasin_id) do nothing;
    insert into public.plans_cheques (fournisseur_reel_id, magasin_id, season, cheques)
    select v_fr, p.magasin_id, p.season, p.cheques
    from public.parametres p where p.fournisseur_id = g.ids[1] and jsonb_typeof(p.cheques) = 'array' and jsonb_array_length(p.cheques) > 0
      and exists (select 1 from public.magasins mg where mg.id = p.magasin_id)
    on conflict (fournisseur_reel_id, magasin_id, season) do nothing;
  end loop;

  -- Contrôles : sinon tout est annulé
  select count(*) into n_marques from public.fournisseurs where fournisseur_reel_id is null;
  if n_marques > 0 then raise exception 'Conversion : % marque(s) sans fournisseur', n_marques; end if;
  select count(*) into n_fr from public.fournisseurs_reels;
  if n_fr <> (select count(distinct coalesce(nullif(btrim(groupe), ''), nom)) from public.fournisseurs) then raise exception 'Conversion : nombre de fournisseurs inattendu'; end if;
  select count(*) into n_modes from public.reglements_fournisseurs;
  select count(*) into n_attendu_modes from public.modes_reglement m
    where m.fournisseur_id in (select min(id) from public.fournisseurs group by coalesce(nullif(btrim(groupe), ''), nom))
      and exists (select 1 from public.magasins mg where mg.id = m.magasin_id);
  if n_modes <> n_attendu_modes then raise exception 'Conversion : % modes recopiés au lieu de %', n_modes, n_attendu_modes; end if;
  select count(*) into n_plans from public.plans_cheques;
  select count(*) into n_attendu_plans from public.parametres p
    where p.fournisseur_id in (select min(id) from public.fournisseurs group by coalesce(nullif(btrim(groupe), ''), nom))
      and jsonb_typeof(p.cheques) = 'array' and jsonb_array_length(p.cheques) > 0 and exists (select 1 from public.magasins mg where mg.id = p.magasin_id);
  if n_plans <> n_attendu_plans then raise exception 'Conversion : % plans chèques recopiés au lieu de %', n_plans, n_attendu_plans; end if;
  raise notice 'Conversion : % marques, % fournisseurs, % modes, % plans chèques', (select count(*) from public.fournisseurs), n_fr, n_modes, n_plans;
end $$;

alter table public.fournisseurs alter column fournisseur_reel_id set not null;

-- Appel venant de l'application (compte connecté ou visiteur) ? Les migrations (psql) et le serveur passent.
-- Fiable aussi dans une fonction « security definer » (où current_user est le propriétaire).
create function public.appel_application() returns boolean
language sql stable set search_path = public, pg_temp as $$
  select coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role', '') in ('authenticated', 'anon')
$$;

-- ─── N4. Une marque créée sans fournisseur reçoit un fournisseur du même nom ; seul la Direction choisit ou change
--         le fournisseur d'une marque (Q9). Les écrans existants (Cahier, imports, Réglages → Marques) continuent de marcher.
create function public.marque_fournisseur() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if tg_op = 'INSERT' then
    if new.fournisseur_reel_id is null then
      insert into public.fournisseurs_reels (nom) values (new.nom) returning id into new.fournisseur_reel_id;
      new.contacts_herites := true;
    elsif public.appel_application() and not public.est_direction() then
      raise exception 'Rattacher une marque à un fournisseur est réservé à la Direction' using errcode = '42501';
    end if;
  elsif new.fournisseur_reel_id is distinct from old.fournisseur_reel_id
        and public.appel_application() and not public.est_direction() then
    raise exception 'Rattacher une marque à un fournisseur est réservé à la Direction' using errcode = '42501';
  end if;
  return new;
end $$;
create trigger marque_fournisseur before insert or update on public.fournisseurs
  for each row execute function public.marque_fournisseur();

-- ─── N9. Fournisseur : nom et clé réservés à la Direction ; contacts modifiables par tous (Q9) ;
--         suppression par la Direction, seulement sans marque, sans plan chèque et sans pointage de chèque (Q4) ───
create function public.fournisseur_garde_fous() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  if tg_op = 'UPDATE' then
    if (new.nom is distinct from old.nom or new.cle_pointage is distinct from old.cle_pointage)
       and public.appel_application() and not public.est_direction() then
      raise exception 'Renommer un fournisseur est réservé à la Direction' using errcode = '42501';
    end if;
    return new;
  end if;
  -- suppression
  if exists (select 1 from public.fournisseurs where fournisseur_reel_id = old.id) then
    raise exception 'Ce fournisseur a encore des marques' using errcode = 'P0001';
  end if;
  if exists (select 1 from public.plans_cheques where fournisseur_reel_id = old.id) then
    raise exception 'Ce fournisseur a un plan de chèques : suppression impossible' using errcode = 'P0001';
  end if;
  if exists (select 1 from public.reglement_paye where cle like 'cheque|' || old.cle_pointage || '|%') then
    raise exception 'Ce fournisseur a des chèques pointés : suppression impossible' using errcode = 'P0001';
  end if;
  return old;
end $$;
create trigger fournisseur_garde_fous before update or delete on public.fournisseurs_reels
  for each row execute function public.fournisseur_garde_fous();

-- ─── N8. Fusionner deux fournisseurs (Direction) — p_essai = true : aperçu sans rien modifier ───
-- Les marques passent au fournisseur gardé ; contacts, règlements et plans chèques : le gardé gagne, l'absorbé comble les
-- trous ; les pointages de chèques de l'absorbé sont rattachés au gardé (Q5) — un pointage déjà présent chez le gardé
-- pour le même chèque est gardé tel quel et celui de l'absorbé reste en base sous son ancienne clé (rien ne se perd).
create function public.fusionner_fournisseurs(p_source bigint, p_cible bigint, p_essai boolean default true)
returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  s public.fournisseurs_reels%rowtype; c public.fournisseurs_reels%rowtype;
  v_marques jsonb; v_regl_repris int; v_regl_ecartes jsonb; v_plans_repris int; v_plans_ecartes jsonb;
  v_pointages int; v_pointages_doublons int; k text; v_coords jsonb;
begin
  if not public.est_direction() then raise exception 'Fusionner des fournisseurs est réservé à la Direction' using errcode = '42501'; end if;
  if p_source = p_cible then raise exception 'Choisir deux fournisseurs différents'; end if;
  select * into s from public.fournisseurs_reels where id = p_source for update;
  select * into c from public.fournisseurs_reels where id = p_cible for update;
  if s.id is null or c.id is null then raise exception 'Fournisseur introuvable'; end if;

  select coalesce(jsonb_agg(nom order by nom), '[]') into v_marques from public.fournisseurs where fournisseur_reel_id = s.id;
  select count(*) into v_regl_repris from public.reglements_fournisseurs r where r.fournisseur_reel_id = s.id
    and not exists (select 1 from public.reglements_fournisseurs x where x.fournisseur_reel_id = c.id and x.magasin_id = r.magasin_id);
  select coalesce(jsonb_agg(jsonb_build_object('magasin_id', r.magasin_id, 'mode', r.mode_reglement, 'condition', r.condition)), '[]') into v_regl_ecartes
    from public.reglements_fournisseurs r where r.fournisseur_reel_id = s.id
    and exists (select 1 from public.reglements_fournisseurs x where x.fournisseur_reel_id = c.id and x.magasin_id = r.magasin_id);
  select count(*) into v_plans_repris from public.plans_cheques p where p.fournisseur_reel_id = s.id
    and not exists (select 1 from public.plans_cheques x where x.fournisseur_reel_id = c.id and x.magasin_id = p.magasin_id and x.season = p.season);
  select coalesce(jsonb_agg(jsonb_build_object('magasin_id', p.magasin_id, 'season', p.season, 'cheques', p.cheques)), '[]') into v_plans_ecartes
    from public.plans_cheques p where p.fournisseur_reel_id = s.id
    and exists (select 1 from public.plans_cheques x where x.fournisseur_reel_id = c.id and x.magasin_id = p.magasin_id and x.season = p.season);
  select count(*) filter (where not exists (select 1 from public.reglement_paye y where y.cle = 'cheque|' || c.cle_pointage || substr(r.cle, length('cheque|' || s.cle_pointage) + 1))),
         count(*) filter (where exists (select 1 from public.reglement_paye y where y.cle = 'cheque|' || c.cle_pointage || substr(r.cle, length('cheque|' || s.cle_pointage) + 1)))
    into v_pointages, v_pointages_doublons
    from public.reglement_paye r where r.cle like 'cheque|' || s.cle_pointage || '|%';

  if not p_essai then
    perform set_config('suivi_pro.par_fonction', 'oui', true);
    update public.fournisseurs set fournisseur_reel_id = c.id where fournisseur_reel_id = s.id;
    perform set_config('suivi_pro.par_fonction', '', true);
    -- contacts : le gardé gagne, l'absorbé comble les trous (par magasin et par champ)
    v_coords := coalesce(c.coords_magasin, '{}');
    for k in select jsonb_object_keys(coalesce(s.coords_magasin, '{}')) loop
      v_coords := jsonb_set(v_coords, array[k], coalesce(s.coords_magasin -> k, '{}') || coalesce(v_coords -> k, '{}'));
    end loop;
    update public.fournisseurs_reels set coords_magasin = v_coords,
      contact = coalesce(nullif(contact, ''), s.contact), telephone = coalesce(nullif(telephone, ''), s.telephone),
      email = coalesce(nullif(email, ''), s.email), contact_sav = coalesce(nullif(contact_sav, ''), s.contact_sav),
      telephone_fixe = coalesce(nullif(telephone_fixe, ''), s.telephone_fixe), numero_client = coalesce(nullif(numero_client, ''), s.numero_client),
      btob = coalesce(nullif(btob, ''), s.btob), contact_compta = coalesce(nullif(contact_compta, ''), s.contact_compta),
      tel_compta = coalesce(nullif(tel_compta, ''), s.tel_compta), email_compta = coalesce(nullif(email_compta, ''), s.email_compta),
      adresse = coalesce(nullif(adresse, ''), s.adresse), notes = coalesce(nullif(notes, ''), s.notes)
    where id = c.id;
    update public.reglements_fournisseurs r set fournisseur_reel_id = c.id where r.fournisseur_reel_id = s.id
      and not exists (select 1 from public.reglements_fournisseurs x where x.fournisseur_reel_id = c.id and x.magasin_id = r.magasin_id);
    delete from public.reglements_fournisseurs where fournisseur_reel_id = s.id;
    update public.plans_cheques p set fournisseur_reel_id = c.id where p.fournisseur_reel_id = s.id
      and not exists (select 1 from public.plans_cheques x where x.fournisseur_reel_id = c.id and x.magasin_id = p.magasin_id and x.season = p.season);
    delete from public.plans_cheques where fournisseur_reel_id = s.id;
    update public.reglement_paye r set cle = 'cheque|' || c.cle_pointage || substr(r.cle, length('cheque|' || s.cle_pointage) + 1)
      where r.cle like 'cheque|' || s.cle_pointage || '|%'
        and not exists (select 1 from public.reglement_paye y where y.cle = 'cheque|' || c.cle_pointage || substr(r.cle, length('cheque|' || s.cle_pointage) + 1));
    -- l'absorbé n'a plus de marque ; s'il garde des pointages en doublon, il reste (« sans marque ») pour ne rien perdre
    if not exists (select 1 from public.reglement_paye where cle like 'cheque|' || s.cle_pointage || '|%') then
      delete from public.fournisseurs_reels where id = s.id;
    end if;
  end if;
  return jsonb_build_object('essai', p_essai, 'source', s.nom, 'cible', c.nom, 'marques', v_marques,
    'reglements_repris', v_regl_repris, 'reglements_ecartes', v_regl_ecartes, 'plans_repris', v_plans_repris,
    'plans_ecartes', v_plans_ecartes, 'pointages_rattaches', v_pointages, 'pointages_deja_chez_le_garde', v_pointages_doublons);
end $$;

-- ─── N10. Vue : chaque fournisseur avec son nombre de marques (« sans marque » quand 0) ───
create view public.fournisseurs_reels_etat with (security_invoker = true) as
select fr.*, (select count(*) from public.fournisseurs m where m.fournisseur_reel_id = fr.id)::int as nb_marques
from public.fournisseurs_reels fr;

